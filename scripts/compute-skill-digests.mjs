#!/usr/bin/env node
/**
 * Computes SHA-256 digests for agent skills index entries.
 * Run: node scripts/compute-skill-digests.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'https://sarvital.com';

function sha256(content) {
  return 'sha256:' + createHash('sha256').update(content, 'utf8').digest('hex');
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`);
  return res.text();
}

const agentsMdUrl = `${origin}/agents.md`;
let sarvitalDigest;
try {
  const agentsBody = await fetchText(agentsMdUrl);
  sarvitalDigest = sha256(agentsBody);
  console.log(`Digest for ${agentsMdUrl}: ${sarvitalDigest}`);
} catch (err) {
  console.warn(`Could not fetch live agents.md (${err.message}); using template placeholder digest`);
  sarvitalDigest = sha256(`sarvital-shop-skill:${origin}/agents.md`);
}

let shopifyDigest;
try {
  const shopSkill = await fetchText('https://shop.app/SKILL.md');
  shopifyDigest = sha256(shopSkill);
  console.log(`Digest for shop.app/SKILL.md: ${shopifyDigest}`);
} catch (err) {
  console.warn(`Could not fetch shop.app SKILL.md (${err.message}); using placeholder`);
  shopifyDigest = sha256('shopify-storefront-skill:https://shop.app/SKILL.md');
}

const index = {
  $schema: 'https://schemas.agentskills.io/discovery/0.2.0/schema.json',
  skills: [
    {
      name: 'sarvital-shop',
      type: 'skill-md',
      description:
        'Browse, search, and purchase Sarvital natural superfood powders (moringa, amla, sattu). Covers product discovery, cart creation, and GoKwik checkout for Indian e-commerce.',
      url: `${origin}/agents.md`,
      digest: sarvitalDigest,
    },
    {
      name: 'shopify-storefront',
      type: 'skill-md',
      description:
        'Generic Shopify storefront skill for reading catalog, managing carts, and initiating checkout via Shopify APIs.',
      url: 'https://shop.app/SKILL.md',
      digest: shopifyDigest,
    },
  ],
};

const outPath = join(root, 'worker', 'well-known-agent-skills-index.json');
writeFileSync(outPath, JSON.stringify(index, null, 2) + '\n');
console.log(`Wrote ${outPath}`);

const constantsPath = join(root, 'worker', 'discovery-constants.js');
const constants = `// Auto-generated by scripts/compute-skill-digests.mjs — do not edit manually
export const SKILL_DIGESTS = {
  sarvital_shop: ${JSON.stringify(sarvitalDigest)},
  shopify_storefront: ${JSON.stringify(shopifyDigest)},
};
`;
writeFileSync(constantsPath, constants);
console.log(`Wrote ${constantsPath}`);

const authMdPath = join(root, 'worker', 'auth-md-content.md');
const authMd = readFileSync(authMdPath, 'utf8');
const authExportPath = join(root, 'worker', 'discovery-auth-md.js');
writeFileSync(
  authExportPath,
  `// Auto-generated from worker/auth-md-content.md\nexport const AUTH_MD = ${JSON.stringify(authMd)};\n`
);
console.log(`Wrote ${authExportPath}`);
